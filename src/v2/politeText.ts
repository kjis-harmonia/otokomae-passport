//   AI への指示でも方言を禁止している。これは指示をすり抜けたときの保険。意味が変わらない語尾だけを置き換える
//   試験：scripts/polite-text.test.mjs
const RULES: [RegExp, string][] = [
  [/じゃけぇ|じゃけん/g, 'なので'],
  [/ますけぇね/g, 'ますね'],
  [/ですけぇね/g, 'ですね'],
  [/けぇね/g, 'ね'],
  [/(ます|です)けぇ/g, '$1ので'],
  [/けぇ/g, 'から'],
  [/しとります/g, 'しています'],
  [/とります/g, 'ています'],
  [/しとる/g, 'している'],
  [/(ん|く)さった/g, '$1ださった'],
  [/のぉ/g, 'ね'],
  [/ええ(です|ね|よ|と思)/g, 'いい$1'],
]
export function politeText(s: string): string {
  return RULES.reduce((t, [re, to]) => t.replace(re, to), s)
}
