/* ── stats ────────────────────────────────────────────────────── */

function pickStats(t: string, cat: StyleCategory): StyleStats {
  let i = 3, s = 3, p = 3, d = 2, r = 3

  // intimidation
  if (inc(t, 'バチバチ', '極道', 'パンチ', '覚醒'))           i = 5
  else if (inc(t, 'アイパー', 'リーゼント', 'ちょい悪', 'ギンパラ', '天空')) i = 4
  else if (inc(t, '昭和', 'トラック', '夜勤', 'カーリー'))     i = 4

  // sexiness
  if (inc(t, '濡れパン', 'スペイン', '夜勤', 'ダンディ'))      s = 5
  else if (inc(t, 'ちょい悪', 'ツイスト', 'スパイラル', 'カーリー', 'ジャマイカン')) s = 4

  // popularity
  if (inc(t, 'ツーブロ', '濡れパン', 'ツイスト', 'スパイラル')) p = 5
  else if (inc(t, 'フェード', 'カラー', 'ブリーチ', 'メッシュ', 'カーリー')) p = 4
  else if (inc(t, 'パンチ', 'アイパー', 'ギンパラ', 'トラック')) p = 2

  // difficulty
  if (inc(t, 'パンチ', '極道', 'ギンパラ', 'カールアイパー', 'バチバチ')) d = 5
  else if (inc(t, 'カラー', 'ブリーチ', 'メッシュ', 'ツイスト', 'スパイラル', 'スペイン')) d = 4
  else if (inc(t, 'パーマ', 'アイパー', 'カーリー', 'フェード')) d = 3

  // durability
  if (inc(t, 'トラック', '夜勤'))                               r = 5
  else if (inc(t, 'パンチ', 'アイパー', '昭和', 'フェード', '白髪')) r = 4

  // category corrections
  if (cat === 'casual') {
    i = Math.min(i, 2)
    s = Math.min(s, 2)
    p = Math.max(p, 3)
    d = Math.min(d, 2)
    r = Math.max(r, 3)
  }
  if (cat === 'premium') {
    i = Math.max(i, 4)
    d = Math.max(d, 3)
  }

  return {
    intimidation: clamp5(i),
    sexiness:     clamp5(s),
    popularity:   clamp5(p),
    difficulty:   clamp5(d),
    durability:   clamp5(r),
  }
}

/* ── public API ───────────────────────────────────────────────── */

/**
 * タイトル（メニュー名）から銀二郎スタイルの下書きを自動生成する。
 * price / durationMinutes / imageUrl / isFeatured / isPublished は生成しない。
 */
export function generateGinjiroDraft(title: string): StyleDraft {
  const cat = pickCategory(title)
  return {
    category:    cat,
    catchCopy:   pickCatchCopy(title, cat),
    description: pickDescription(title, cat),
    tags:        pickTags(title),
    stats:       pickStats(title, cat),
  }
}
